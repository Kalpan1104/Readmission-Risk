"""
Evaluate the model overall and per subgroup, apply the release gate, and
write a model card.

The gate fails the build if the model is weak overall OR if it works much
worse for one group (sex or age band) than for patients as a whole.

Usage: python -m src.evaluate --dir reports --version v1.0.0
Exit code 1 means the gate failed.
"""
import argparse
import json
import os
import sys
from datetime import date
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
from sklearn.metrics import brier_score_loss, precision_score, recall_score, roc_auc_score

from src import config as C


def age_band(age):
    return pd.cut(age, bins=[0, 49, 64, 79, 200], labels=["18-49", "50-64", "65-79", "80+"])


def metrics(y, p, threshold=C.DECISION_THRESHOLD):
    y, p = np.asarray(y), np.asarray(p)
    flag = (p >= threshold).astype(int)
    return {
        "n": int(len(y)),
        "readmit_rate": round(float(y.mean()), 3),
        "auc": round(float(roc_auc_score(y, p)), 3) if len(set(y)) == 2 else None,
        "recall": round(float(recall_score(y, flag, zero_division=0)), 3),
        "precision": round(float(precision_score(y, flag, zero_division=0)), 3),
        "flag_rate": round(float(flag.mean()), 3),
        "brier": round(float(brier_score_loss(y, p)), 4),
    }


def subgroup_metrics(df, p):
    groups = {"sex": df["sex"], "age_band": age_band(df["age"])}
    out = {}
    for name, col in groups.items():
        out[name] = {}
        for value in col.dropna().unique():
            mask = (col == value).to_numpy()
            out[name][str(value)] = metrics(df[C.TARGET].to_numpy()[mask], p[mask])
    return out


def gate(overall, subgroups):
    reasons = []
    if overall["auc"] < C.MIN_AUC:
        reasons.append(f"overall AUC {overall['auc']} < {C.MIN_AUC}")
    if overall["recall"] < C.MIN_RECALL:
        reasons.append(f"recall {overall['recall']} < {C.MIN_RECALL}")
    for name, groups in subgroups.items():
        aucs = {g: m["auc"] for g, m in groups.items()
                if m["n"] >= C.MIN_SUBGROUP_SIZE and m["auc"] is not None}
        for g, auc in aucs.items():
            drop = overall["auc"] - auc
            if drop > C.MAX_SUBGROUP_AUC_DROP:
                reasons.append(f"{name}={g}: AUC {auc} is {drop:.3f} below overall "
                               f"(limit {C.MAX_SUBGROUP_AUC_DROP})")
    return reasons


def model_card(version, overall, subgroups, reasons, top_features):
    passed = not reasons
    lines = [
        f"# Model card: 30-day readmission risk `{version}`",
        "",
        f"*Generated {date.today().isoformat()} by GitHub Actions.*",
        "",
        "## What it does",
        "Estimates the chance a patient is readmitted within 30 days of discharge, so a care team "
        f"can prioritise follow-up calls. Patients scoring at or above **{C.DECISION_THRESHOLD}** are flagged.",
        "",
        "## Data",
        "Trained on **synthetic** discharge records generated by `src/synth.py`. "
        "No real patient data is used anywhere in this project, and this model must not be used for real care decisions.",
        "",
        "## Overall performance (held-out set)",
        "| n | Readmit rate | AUC | Recall | Precision | Flag rate | Brier |",
        "|---|---|---|---|---|---|---|",
        "| {n} | {readmit_rate} | {auc} | {recall} | {precision} | {flag_rate} | {brier} |".format(**overall),
        "",
        "## Performance by subgroup",
    ]
    for name, groups in subgroups.items():
        lines += ["", f"**{name}**", "", "| Group | n | Readmit rate | AUC | Recall | Flag rate |",
                  "|---|---|---|---|---|---|"]
        for g in sorted(groups):
            m = groups[g]
            lines.append(f"| {g} | {m['n']} | {m['readmit_rate']} | {m['auc']} | {m['recall']} | {m['flag_rate']} |")
    lines += ["", "## Strongest signals (standardised coefficients)", "",
              "| Feature | Coefficient |", "|---|---|",
              *[f"| {f} | {c} |" for f, c in top_features],
              "", "## Release gate",
              f"Rules: AUC ≥ {C.MIN_AUC}, recall ≥ {C.MIN_RECALL}, no subgroup more than {C.MAX_SUBGROUP_AUC_DROP} AUC below overall "
              f"(groups with ≥ {C.MIN_SUBGROUP_SIZE} patients).", ""]
    lines.append("**✅ Passed**" if passed else "**❌ Failed**\n\n" + "\n".join(f"- {r}" for r in reasons))
    lines += ["", "## Known limitations",
              "- Synthetic data is cleaner than real EHR data.",
              "- AUC inside a single age band is naturally lower than overall, because age itself is one of "
              "the predictors and a narrow band removes that spread. Small bands are also noisy.",
              "- Only sex and age band are checked for fairness; real deployments should also look at "
              "race/ethnicity, payer and language where it's lawful and appropriate to do so.",
              "- The threshold trades precision for recall on purpose; a care team with limited capacity may want it higher."]
    return "\n".join(lines) + "\n"


def main(report_dir, version):
    d = Path(report_dir)
    model = joblib.load(d / "model.joblib")
    test = pd.read_csv(d / "test_set.csv")
    top = json.loads((d / "top_features.json").read_text())

    p = model.predict_proba(test[C.NUMERIC + C.CATEGORICAL])[:, 1]
    overall = metrics(test[C.TARGET], p)
    subgroups = subgroup_metrics(test, p)
    reasons = gate(overall, subgroups)

    card = model_card(version, overall, subgroups, reasons, top)
    (d / "model_card.md").write_text(card)
    (d / "metrics.json").write_text(json.dumps(
        {"version": version, "overall": overall, "subgroups": subgroups,
         "gate_passed": not reasons, "gate_failures": reasons}, indent=2))

    if os.environ.get("GITHUB_STEP_SUMMARY"):
        with open(os.environ["GITHUB_STEP_SUMMARY"], "a") as f:
            f.write(card)
    print(card)
    return overall, subgroups, reasons


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--dir", default="reports")
    p.add_argument("--version", default="dev")
    a = p.parse_args()
    _, _, failures = main(a.dir, a.version)
    sys.exit(1 if failures else 0)
